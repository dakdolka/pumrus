def _cards(seeds: list[tuple[str, str, str]], topic_code: str) -> list[dict[str, Any]]:
    cards = []
    for mask, answer, explanation in seeds:
        cards.append({
            "type": "vowel_fill",
            "prompt": mask,
            "answer": answer,
            "explanation": explanation,
            "topic_code": topic_code,
            "source_references": REFERENCES,
        })
    assert len(cards) == len(seeds)
    assert len({item["prompt"] for item in cards}) == len(cards)
    return cards


def _marked_seeds(marked_words: str, explanation: str) -> list[tuple[str, str, str]]:
    seeds = []
    for marked in marked_words.split():
        positions = [
            index for index, character in enumerate(marked)
            if character in "АЕЁИОУЫЭЮЯ"
        ]
        if len(positions) != 1:
            raise ValueError(f"Expected one marked vowel in {marked!r}")
        index = positions[0]
        answer = marked.lower()
        seeds.append((answer[:index] + "_" + answer[index + 1:], answer, explanation))
    return seeds


def _expand_to_200(
    seeds: list[tuple[str, str, str]],
    groups: list[tuple[str, str]],
) -> list[tuple[str, str, str]]:
    result = list(seeds)
    seen = {mask for mask, _, _ in result}
    for marked_words, explanation in groups:
        for seed in _marked_seeds(marked_words, explanation):
            if seed[0] in seen:
                continue
            seen.add(seed[0])
            result.append(seed)
            if len(result) == 200:
                return result
    raise ValueError(f"Only {len(result)} unique task 9 seeds were prepared")


