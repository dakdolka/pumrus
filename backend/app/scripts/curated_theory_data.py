def text(markdown: str, *, variant: str | None = None) -> dict[str, Any]:
    settings = {"variant": variant} if variant else {}
    return {"type": "rich_text", "data": {"markdown": markdown}, "settings": settings}


def callout(markdown: str, variant: str = "rule") -> dict[str, Any]:
    return {
        "type": "callout",
        "data": {"markdown": markdown, "variant": variant},
        "settings": {},
    }


def example(markdown: str) -> dict[str, Any]:
    return {"type": "example", "data": {"markdown": markdown}, "settings": {}}


def items(*values: str, ordered: bool = False) -> dict[str, Any]:
    return {
        "type": "list",
        "data": {"style": "ordered" if ordered else "unordered", "items": list(values)},
        "settings": {},
    }


def table(*rows: list[str]) -> dict[str, Any]:
    return {
        "type": "table",
        "data": {"rows": [{"cells": list(row)} for row in rows]},
        "settings": {},
    }


