REVISION = "ege-2026-orthography-v1"


def heading(value: str) -> dict[str, Any]:
    return text(value, variant="heading_2")


def topic(
    code: str,
    title: str,
    description: str,
    *blocks: dict[str, Any],
) -> dict[str, Any]:
    return {
        "code": code,
        "title": title,
        "description": description,
        "blocks": list(blocks),
    }


def bundle(
    number: int,
    title: str,
    short_description: str,
    intro_blocks: list[dict[str, Any]],
    topics: list[dict[str, Any]],
) -> dict[str, Any]:
    return {
        "number": number,
        "revision": f"{REVISION}-task-{number}",
        "sources": [
            f"umrus_theory_stuff/{number}",
            "umrus_theory_stuff/9-15",
        ],
        "title": f"Задание {number}. {title}",
        "short_description": short_description,
        "document_title": f"Как решать задание {number}",
        "blocks": intro_blocks,
        "topics": topics,
    }


