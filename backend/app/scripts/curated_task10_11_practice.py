CARDS: list[dict[str, Any]] = []


def group(topic: str, rule: str, words: str, explanation: str, *, exception=False):
    for marked in words.split():
        positions = [i for i, c in enumerate(marked) if c.isupper()]
        if not positions or any(marked[i].lower() not in "абвгдеёжзийклмнопрстуфхцчшщъыьэюя" for i in positions):
            raise ValueError(f"Mark the tested Cyrillic letter(s): {marked}")
        word = marked.lower()
        mask = "".join("_" if i in positions else c for i, c in enumerate(word))
        letter = "".join(word[i] for i in positions)
        text = explanation.format(word=word, letter=letter.upper(), following=word[positions[-1] + 1:positions[-1] + 2].upper())
        if rule == "prefix-zs" and word[positions[-1] + 1:positions[-1] + 2] in "аеёиоуыэюя":
            text = "В приставке на з-/с- перед гласной пишется **З**. Здесь после приставки начинается гласная основы."
        task, code, _ = TOPICS[topic]
        key = hashlib.sha256(f"{task}:{code}:{word}".encode()).hexdigest()[:16]
        CARDS.append({"type": "vowel_fill", "prompt": mask, "answer": word, "lexeme": word,
                      "explanation": f"**{word}**. {text}", "is_exception": exception,
                      "topic_code": code, "task_number": task, "rule_id": rule,
                      "curated_key": f"task{task}-verified:{key}", "source_references": [FIPI, RAN]})


def context(word: str, phrase: str, explanation: str):
    """Replace one card's context without creating another word occurrence."""
    card = next(card for card in reversed(CARDS) if card["lexeme"] == word)
    if phrase.count(word) != 1:
        raise ValueError(f"Context must contain the tested word once: {phrase}")
    card["answer"] = phrase
    card["prompt"] = phrase.replace(word, card["prompt"], 1)
    card["explanation"] = f"**{phrase}**. {explanation}"


