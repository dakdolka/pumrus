def candidate_cards() -> list[dict[str, Any]]:
    """Deduplicate authored lexical entries; spelling gate runs separately."""
    result: dict[tuple[str, str], dict[str, Any]] = {}
    for card in CARDS:
        if card["rule_id"] == "roz-stressed" and card["lexeme"] in {"розница", "розничный"}:
            continue  # root writing belongs outside the task 10 prefix bank
        key = (card["topic_code"], card["lexeme"].replace("ё", "е"))
        result.setdefault(key, card)
    return list(result.values())


def reviewed_cards(evidence: dict[str, Any]) -> list[dict[str, Any]]:
    """Unverified or differently spelled words never enter the public bank."""
    cards = []
    for card in candidate_cards():
        record = evidence.get(card["lexeme"])
        if not record or record.get("status") != "verified":
            continue
        cards.append({**card, "source_references": [*card["source_references"], record["url"]], "dictionary_evidence": record})
    return cards
