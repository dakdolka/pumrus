def heading(value: str) -> dict[str, Any]:
    return text(value, variant="heading_2")


def topic(
    code: str,
    title: str,
    description: str,
    *blocks: dict[str, Any],
) -> dict[str, Any]:
    return {
        "code": code,
        "title": title,
        "description": description,
        "blocks": list(blocks),
    }


def bundle(
    number: int,
    title: str,
    short_description: str,
    intro_blocks: list[dict[str, Any]],
    topics: list[dict[str, Any]],
    *extra_sources: str,
) -> dict[str, Any]:
    return {
        "number": number,
        "revision": f"{REVISION}-task-{number}",
        "sources": [*COMMON_SOURCES, *extra_sources],
        "title": f"Задание {number}. {title}",
        "short_description": short_description,
        "document_title": f"Как решать задание {number}",
        "blocks": intro_blocks,
        "topics": topics,
    }


