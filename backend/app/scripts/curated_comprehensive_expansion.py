def _source_topic(task_number: int, code: str) -> dict[str, Any]:
    for candidate in _BUNDLES[task_number]["topics"]:
        if candidate["code"] == code:
            return candidate
    raise KeyError(f"Topic {code!r} was not found in task {task_number}")


def _expanded_topic(task_number: int, code: str) -> dict[str, Any]:
    source = deepcopy(_source_topic(task_number, code))
    source["task_number"] = task_number
    source["code"] = f"{code}-complete-2026"
    source["blocks"].extend(deepcopy(EXTRA_BLOCKS.get(code, [])))
    return source


