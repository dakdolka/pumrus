def _position_item(
    prompt: str,
    answer: list[str],
    topic_code: str,
    explanation: str,
) -> dict[str, Any]:
    highest = max(int(value) for value in answer)
    visible = max(
        (int(value) for value in re.findall(r"\((\d+)\)", prompt)),
        default=highest,
    )
    return {
        "type": "multiple_choice",
        "prompt": prompt,
        "options": [str(index) for index in range(1, visible + 1)],
        "answer": answer,
        "explanation": explanation,
        "topic_code": topic_code,
    }


