def _choice(
    prompt: str,
    options: list[str],
    answer: str,
    explanation: str,
    topic_code: str,
) -> dict[str, Any]:
    return {
        "type": "single_choice",
        "prompt": prompt,
        "options": options,
        "answer": answer,
        "explanation": explanation,
        "topic_code": topic_code,
    }


