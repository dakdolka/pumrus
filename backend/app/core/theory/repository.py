from abc import ABC

from app.infra.theory.models import TaskTheoryGroupBD
from .entities import Theory, TheoryBlock, TheoryType, TheorySubject, TaskTheoryGroup
from sqlalchemy.ext.asyncio import AsyncSession
from typing import Tuple, List

class ITheoryRepository(ABC):
    async def create_theory_types_and_subjs(self, session: AsyncSession, subject2type_config: dict): ...
    async def create_theory(self, session: AsyncSession, theory: Theory, subject) -> int: ...
    async def get_theory_by_id(self, session: AsyncSession, id: int) -> Theory: ...
    async def get_all_theories_for_subject(self, session: AsyncSession, subject_id: int) -> List[tuple[int, str]]: ...
    async def get_all_theory_dop_info(self, session: AsyncSession) -> List[dict]: ...
    async def get_all_task_groups_for_subject(self, session: AsyncSession, subject_id: int) -> List[TaskTheoryGroup]: ...
    async def get_theories_by_names(self, session: AsyncSession, names: List[str]) -> List[int]: ...
    async def insert_task_theory_group(self, session: AsyncSession, task_theory_group: TaskTheoryGroup): ...
    async def get_all_task_groups_for_subject(self, session: AsyncSession, subject_id: int) -> List[TaskTheoryGroupBD]: ...
    async def get_all_subjects(self, session: AsyncSession, subject_id: int | None) -> List[TheorySubject]: ...